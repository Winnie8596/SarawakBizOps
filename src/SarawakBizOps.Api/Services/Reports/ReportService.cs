using Microsoft.EntityFrameworkCore;
using SarawakBizOps.Api.Data;
using SarawakBizOps.Api.Data.Configurations;
using SarawakBizOps.Api.DTOs.Reports;
using SarawakBizOps.Api.DTOs.WorkOrders;
using SarawakBizOps.Api.Models.Entities;
using SarawakBizOps.Api.Models.Enums;
using SarawakBizOps.Api.Services.Common;
using SarawakBizOps.Api.Services.Reports.Pdf;
using SarawakBizOps.Api.Services.Storage;
using SarawakBizOps.Api.Services.WorkOrders;

namespace SarawakBizOps.Api.Services.Reports;

public class ReportService : IReportService
{
    private const string ChangedMessage = "The report was just generated by someone else. Refresh to see it.";

    private readonly ApplicationDbContext _db;
    private readonly IFileStorage _storage;
    private readonly IWorkOrderService _workOrders;
    private readonly ILogger<ReportService> _logger;

    public ReportService(
        ApplicationDbContext db, IFileStorage storage, IWorkOrderService workOrders, ILogger<ReportService> logger)
    {
        _db = db;
        _storage = storage;
        _workOrders = workOrders;
        _logger = logger;
    }

    public async Task<ServiceResult<WorkOrderDto>> GenerateAsync(int workOrderId, string actingUserId, CancellationToken ct)
    {
        var workOrder = await _db.WorkOrders.AsNoTracking()
            .Include(w => w.ServiceRequest!).ThenInclude(r => r.Customer)
            .Include(w => w.ServiceRequest!).ThenInclude(r => r.Equipment)
            .Include(w => w.Technician)
            .Include(w => w.PartsUsed).ThenInclude(p => p.Part)
            .Include(w => w.Photos).ThenInclude(p => p.UploadedByUser)
            .Include(w => w.ServiceReport)
            .AsSplitQuery()
            .FirstOrDefaultAsync(w => w.Id == workOrderId, ct);
        if (workOrder is null)
        {
            return ServiceResult<WorkOrderDto>.Fail(ServiceErrorKind.NotFound, "Work order not found.");
        }

        var existing = workOrder.ServiceReport;
        if (ReportRules.GenerateRefusal(workOrder.Status, existing?.ReportNumber) is { } refused)
        {
            return ServiceResult<WorkOrderDto>.Fail(ServiceErrorKind.Conflict, refused);
        }

        // A completed job can no longer change (every technician edit needs InProgress), so what was read above is
        // the snapshot the report documents. Rendering and the upload happen outside any transaction; the database
        // write at the end re-checks, under the job row's lock, that nothing moved on in the meantime.
        var generatedAt = DateTime.UtcNow;
        var reportNumber = existing?.ReportNumber
            ?? ReportRules.FormatNumber(ReportRules.ToMyt(generatedAt).Year, await NextSequenceAsync(ct));
        var revision = (existing?.Revision ?? 0) + 1;
        var generatedBy = await _db.Users.AsNoTracking()
            .Where(u => u.Id == actingUserId)
            .Select(u => u.FullName)
            .FirstOrDefaultAsync(ct) ?? string.Empty;

        var model = ServiceReportBuilder.Build(workOrder, reportNumber, revision, generatedAt, generatedBy);
        var (photos, signature) = await LoadImagesAsync(workOrder, ct);
        var pdf = ServiceReportRenderer.Render(model, photos, signature);

        var key = ReportRules.NewKey(workOrderId);
        using (var content = new MemoryStream(pdf, writable: false))
        {
            await _storage.SaveAsync(key, content, ReportRules.ContentType, ct);
        }

        var committing = false;
        try
        {
            await using var tx = await _db.Database.BeginTransactionAsync(ct);

            // UPDLOCK on the job row until commit: an Approve (whose UPDATE needs that row) waits for this write
            // instead of slipping in between the check and it, and two Managers generating at once take turns.
            var status = (await _db.Database
                    .SqlQuery<string>($"SELECT [Status] AS [Value] FROM [WorkOrders] WITH (UPDLOCK, ROWLOCK) WHERE [Id] = {workOrderId}")
                    .ToListAsync(ct))
                .SingleOrDefault();
            var current = await _db.ServiceReports.AsNoTracking()
                .Where(r => r.WorkOrderId == workOrderId)
                .Select(r => new { r.ReportNumber, r.Revision })
                .FirstOrDefaultAsync(ct);

            var refusedNow = status is null
                ? "Work order not found."
                : ReportRules.GenerateRefusal(Enum.Parse<WorkOrderStatus>(status), current?.ReportNumber);
            if (refusedNow is not null || current?.Revision != existing?.Revision)
            {
                // The job was approved, or someone else generated the report, after it was read above: the PDF just
                // rendered carries a number or revision that is no longer right.
                await tx.RollbackAsync(ct);
                await DeleteQuietlyAsync(key, workOrderId);
                return ServiceResult<WorkOrderDto>.Fail(
                    status is null ? ServiceErrorKind.NotFound : ServiceErrorKind.Conflict, refusedNow ?? ChangedMessage);
            }

            if (existing is null)
            {
                _db.ServiceReports.Add(new ServiceReport
                {
                    WorkOrderId = workOrderId,
                    ReportNumber = reportNumber,
                    Revision = revision,
                    BlobKey = key,
                    SizeBytes = pdf.Length,
                    GeneratedByUserId = actingUserId,
                    GeneratedAt = generatedAt
                });
                await _db.SaveChangesAsync(ct);
            }
            else
            {
                await _db.ServiceReports
                    .Where(r => r.WorkOrderId == workOrderId && r.Revision == existing.Revision)
                    .ExecuteUpdateAsync(s => s
                        .SetProperty(r => r.Revision, revision)
                        .SetProperty(r => r.BlobKey, key)
                        .SetProperty(r => r.SizeBytes, pdf.Length)
                        .SetProperty(r => r.GeneratedByUserId, actingUserId)
                        .SetProperty(r => r.GeneratedAt, generatedAt), ct);
            }

            committing = true;
            await tx.CommitAsync(ct);
        }
        catch when (!committing)
        {
            // Nothing points at the new file. (A failed commit is ambiguous, so the file is kept then: an orphan
            // at worst, never a report pointing at a deleted file.)
            await DeleteQuietlyAsync(key, workOrderId);
            throw;
        }

        // Only now does nothing point at the previous rendering.
        if (existing is not null)
        {
            await DeleteQuietlyAsync(existing.BlobKey, workOrderId);
        }

        _logger.LogInformation(
            "WorkOrder {WorkOrderId}: service report {ReportNumber} revision {Revision} generated by {UserId} " +
            "({Bytes} bytes, {Pictured}/{Photos} photos pictured)",
            workOrderId, reportNumber, revision, actingUserId, pdf.Length, photos.Count(p => p is not null), photos.Count);

        return await _workOrders.GetByIdAsync(workOrderId, actingUserId, requireOwnTechnician: false, ct);
    }

    public async Task<ServiceResult<(StoredFile File, string ReportNumber)>> OpenAsync(
        int workOrderId, string actingUserId, bool requireOwnTechnician, CancellationToken ct)
    {
        var row = await _db.WorkOrders.AsNoTracking()
            .Where(w => w.Id == workOrderId)
            .Select(w => new
            {
                w.TechnicianId,
                Report = w.ServiceReport == null ? null : new { w.ServiceReport.BlobKey, w.ServiceReport.ReportNumber }
            })
            .FirstOrDefaultAsync(ct);
        if (row is null || (requireOwnTechnician && row.TechnicianId != actingUserId))
        {
            return ServiceResult<(StoredFile, string)>.Fail(ServiceErrorKind.NotFound, "Work order not found.");
        }

        if (row.Report is null)
        {
            return ServiceResult<(StoredFile, string)>.Fail(ServiceErrorKind.NotFound, "This job has no service report yet.");
        }

        var file = await _storage.OpenReadAsync(row.Report.BlobKey, ct);
        if (file is null)
        {
            _logger.LogWarning("WorkOrder {WorkOrderId} report {ReportNumber} points at {Key}, which is missing from storage",
                workOrderId, row.Report.ReportNumber, row.Report.BlobKey);
            return ServiceResult<(StoredFile, string)>.Fail(ServiceErrorKind.NotFound, "The report file could not be found.");
        }

        return ServiceResult<(StoredFile, string)>.Ok((file, row.Report.ReportNumber));
    }

    public async Task<IReadOnlyList<ServiceReportDto>> GetAllAsync(CancellationToken ct)
        => await _db.ServiceReports.AsNoTracking()
            .OrderByDescending(r => r.GeneratedAt)
            .ThenByDescending(r => r.Id)
            .Select(r => new ServiceReportDto
            {
                Id = r.Id,
                ReportNumber = r.ReportNumber,
                Revision = r.Revision,
                GeneratedAt = r.GeneratedAt,
                GeneratedByName = r.GeneratedByUser!.FullName,
                SizeBytes = r.SizeBytes,
                IsLocked = r.WorkOrder!.Status == WorkOrderStatus.Approved || r.WorkOrder.Status == WorkOrderStatus.Cancelled,
                WorkOrderId = r.WorkOrderId,
                WorkOrderStatus = r.WorkOrder.Status.ToString(),
                CustomerName = r.WorkOrder.ServiceRequest!.Customer!.CompanyName,
                EquipmentSerialNumber = r.WorkOrder.ServiceRequest.Equipment!.SerialNumber,
                EquipmentType = r.WorkOrder.ServiceRequest.Equipment.EquipmentType,
                TechnicianName = r.WorkOrder.Technician == null ? string.Empty : r.WorkOrder.Technician.FullName,
                CompletedAt = r.WorkOrder.CompletedAt
            })
            .ToListAsync(ct);

    private const string NextNumberSql =
        "SELECT NEXT VALUE FOR [" + ServiceReportConfiguration.NumberSequence + "] AS [Value]";

    // NEXT VALUE FOR cannot sit inside a derived table, so the query is run as written, never composed on.
    private async Task<long> NextSequenceAsync(CancellationToken ct)
        => (await _db.Database.SqlQueryRaw<long>(NextNumberSql).ToListAsync(ct)).Single();

    /// <summary>
    /// The pictures for the report, read from storage one at a time: the signature and each photo, shrunk where
    /// they can be (PNG) and within the embedded-size cap where they cannot (JPEG). A missing or unreadable file
    /// becomes a placeholder, never a failed report.
    /// </summary>
    private async Task<(IReadOnlyList<PdfImage?> Photos, PdfImage? Signature)> LoadImagesAsync(WorkOrder workOrder, CancellationToken ct)
    {
        PdfImage? signature = null;
        if (workOrder.SignatureBlobKey is { } signatureKey && await ReadAsync(signatureKey, workOrder.Id, ct) is { } png)
        {
            signature = PdfImage.FromPng(new MemoryStream(png, writable: false), ReportRules.SignatureMaxSide);
        }

        var photos = new List<PdfImage?>();
        var jpegBudget = ReportRules.MaxEmbeddedJpegBytes;
        foreach (var photo in workOrder.Photos.OrderBy(p => p.UploadedAt).ThenBy(p => p.Id))
        {
            PdfImage? image = null;
            if (photo.ContentType == PhotoRules.Png && await ReadAsync(photo.BlobKey, workOrder.Id, ct) is { } pngBytes)
            {
                image = PdfImage.FromPng(new MemoryStream(pngBytes, writable: false), ReportRules.PhotoThumbnailMaxSide);
            }
            else if (photo.ContentType == PhotoRules.Jpeg && photo.SizeBytes <= jpegBudget
                     && await ReadAsync(photo.BlobKey, workOrder.Id, ct) is { } jpegBytes)
            {
                image = PdfImage.FromJpeg(jpegBytes);
                if (image is not null)
                {
                    jpegBudget -= jpegBytes.Length;
                }
            }
            // WebP (only on photos stored before uploads refused it) has no PDF filter: listed, not pictured.

            photos.Add(image);
        }

        return (photos, signature);
    }

    private async Task<byte[]?> ReadAsync(string key, int workOrderId, CancellationToken ct)
    {
        var file = await _storage.OpenReadAsync(key, ct);
        if (file is null)
        {
            _logger.LogWarning("WorkOrder {WorkOrderId}: {Key} is missing from storage; the report shows a placeholder",
                workOrderId, key);
            return null;
        }

        await using (file.Content)
        {
            using var buffer = new MemoryStream();
            await file.Content.CopyToAsync(buffer, ct);
            return buffer.ToArray();
        }
    }

    // Cleanup after the database has already decided; a failure here leaves an orphaned file (logged), never a
    // report pointing at a missing one, so it must not turn a correct response into an error.
    private async Task DeleteQuietlyAsync(string key, int workOrderId)
    {
        try
        {
            await _storage.DeleteAsync(key, CancellationToken.None);
        }
        catch (Exception ex)
        {
            _logger.LogWarning(ex, "Could not delete unused report file {Key} of WorkOrder {WorkOrderId}", key, workOrderId);
        }
    }
}
