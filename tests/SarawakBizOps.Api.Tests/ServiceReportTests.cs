/// <summary>
/// Phase 10: the service report PDF (PRD §6.7, SDD §15, BR-14 per D-05) — generated by a Manager from the
/// completed job, uniquely numbered, stored through IFileStorage (Azurite here), locked once the job is approved,
/// and readable only through the authorized download endpoint.
/// </summary>
[Collection(ApiCollection.Name)]
public class ServiceReportTests
{
    private static readonly Regex ReportNumber = new(@"^SR-\d{4}-\d{6,}$");

    private readonly ApiFactory _factory;

    public ServiceReportTests(ApiFactory factory) => _factory = factory;

    private static async Task<string> DetailAsync(HttpResponseMessage response)
        => (await response.Content.ReadFromJsonAsync<ProblemDetails>())!.Detail ?? string.Empty;

    private sealed record Job(HttpClient Admin, HttpClient Manager, HttpClient Technician, TestUser TechnicianUser, WorkOrderDto WorkOrder);

    /// <summary>A completed job with a part, a PNG and a JPEG photo and the customer's signature.</summary>
    private async Task<Job> CompletedJobAsync(WebApplicationFactory<Program>? host = null)
    {
        var admin = await _factory.AdminClientAsync();
        var managerUser = await TestUsers.CreateAsync(admin, AppRoles.Manager);
        var technicianUser = await TestUsers.CreateAsync(admin, AppRoles.Technician);
        WebApplicationFactory<Program> app = host ?? _factory;
        var manager = await app.SignInAsync(managerUser);
        var technician = await app.SignInAsync(technicianUser);

        var job = await CreateInProgressWorkOrderAsync(admin, manager, technician, technicianUser.Id);
        var part = await CreateStockedPartAsync(admin, onHand: 5, unitCost: 145.00m);
        await AddPartAsync(technician, job.Id, part.Id, 2);
        await UploadPhotoAsync(technician, job.Id, PhotoPng);
        await UploadPhotoAsync(technician, job.Id, TestJpeg.Create(320, 240, orientation: 6));
        await SaveDiagnosisAsync(technician, job.Id);
        await UploadSignatureAsync(technician, job.Id);
        var completed = await CompleteWorkOrderAsync(technician, job.Id);
        return new Job(admin, manager, technician, technicianUser, completed);
    }

    private async Task<List<(string ReportNumber, int Revision, string BlobKey)>> ReportRowsAsync(int workOrderId)
    {
        using var scope = _factory.Services.CreateScope();
        var db = scope.ServiceProvider.GetRequiredService<ApplicationDbContext>();
        return (await db.ServiceReports.AsNoTracking()
                .Where(r => r.WorkOrderId == workOrderId)
                .Select(r => new { r.ReportNumber, r.Revision, r.BlobKey })
                .ToListAsync())
            .Select(r => (r.ReportNumber, r.Revision, r.BlobKey))
            .ToList();
    }

    private static List<string> ReportFiles(InMemoryFileStorage storage, int workOrderId)
        => storage.Keys.Where(k => k.StartsWith($"work-orders/{workOrderId}/report-")).ToList();

    // ---- Generating and reading back ----

    [Fact]
    public async Task A_manager_generates_a_numbered_report_that_every_reader_of_the_job_can_download()
    {
        var job = await CompletedJobAsync();
        var staff = await _factory.ClientWithRoleAsync(AppRoles.ServiceStaff);

        var response = await PostGenerateReportAsync(job.Manager, job.WorkOrder.Id);
        var json = await response.Content.ReadAsStringAsync();

        Assert.Equal(HttpStatusCode.OK, response.StatusCode);
        var report = (await response.Content.ReadFromJsonAsync<WorkOrderDto>())!.Report!;
        Assert.Matches(ReportNumber, report.ReportNumber);
        Assert.StartsWith($"SR-{ReportRules.ToMyt(DateTime.UtcNow).Year}-", report.ReportNumber);
        Assert.Equal((1, "Test Manager", false), (report.Revision, report.GeneratedByName, report.IsLocked));
        Assert.True(report.SizeBytes > 0);
        Assert.DoesNotContain("work-orders/", json); // no storage key leaves the API

        foreach (var reader in new[] { job.Manager, job.Admin, staff, job.Technician })
        {
            var download = await reader.GetAsync($"/api/work-orders/{job.WorkOrder.Id}/report");
            var bytes = await download.Content.ReadAsByteArrayAsync();

            Assert.Equal(HttpStatusCode.OK, download.StatusCode);
            Assert.Equal("application/pdf", download.Content.Headers.ContentType!.MediaType);
            Assert.Equal($"{report.ReportNumber}.pdf", download.Content.Headers.ContentDisposition!.FileNameStar
                ?? download.Content.Headers.ContentDisposition.FileName);
            Assert.Equal("nosniff", download.Headers.GetValues("X-Content-Type-Options").Single());
            Assert.Contains("no-store", download.Headers.CacheControl!.ToString());
            Assert.Equal(report.SizeBytes, bytes.Length);
            Assert.StartsWith("%PDF-1.4", Encoding.ASCII.GetString(bytes, 0, 8));
        }

        // The technician sees the report on their own job too (PRD §6.8: "… Complete → View Report").
        Assert.Equal(report.ReportNumber, (await GetWorkOrderAsync(job.Technician, job.WorkOrder.Id))!.Report!.ReportNumber);
    }

    [Fact]
    public async Task The_pdf_is_built_from_the_completed_job_with_its_photos_and_signature_pictured()
    {
        var job = await CompletedJobAsync();

        var report = (await GenerateReportAsync(job.Manager, job.WorkOrder.Id)).Report!;
        var pdf = Encoding.Latin1.GetString(await job.Manager.GetByteArrayAsync($"/api/work-orders/{job.WorkOrder.Id}/report"));

        Assert.Contains($"/Title (Service report {report.ReportNumber})", pdf);
        // The PNG photo (as a thumbnail), the JPEG photo (as-is) and the signature.
        Assert.Equal(3, Regex.Matches(pdf, "/Subtype /Image").Count);
        Assert.Contains("/Width 320 /Height 240 /ColorSpace /DeviceRGB /BitsPerComponent 8 /Filter /DCTDecode", pdf);
        Assert.EndsWith("%%EOF\n", pdf);
    }

    [Fact]
    public async Task Regenerating_a_completed_job_keeps_the_number_bumps_the_revision_and_replaces_the_file()
    {
        var storage = new InMemoryFileStorage();
        await using var host = _factory.WithFileStorage(storage);
        var job = await CompletedJobAsync(host);

        var first = (await GenerateReportAsync(job.Manager, job.WorkOrder.Id)).Report!;
        var firstFile = Assert.Single(ReportFiles(storage, job.WorkOrder.Id));
        var second = (await GenerateReportAsync(job.Manager, job.WorkOrder.Id)).Report!;

        Assert.Equal(first.ReportNumber, second.ReportNumber);
        Assert.Equal((1, 2), (first.Revision, second.Revision));
        var (number, revision, key) = Assert.Single(await ReportRowsAsync(job.WorkOrder.Id));
        Assert.Equal((first.ReportNumber, 2), (number, revision));
        Assert.Equal(key, Assert.Single(ReportFiles(storage, job.WorkOrder.Id))); // the old rendering was deleted
        Assert.NotEqual(firstFile, key);
    }

    [Fact]
    public async Task Once_the_job_is_approved_its_report_is_locked_and_cannot_be_regenerated()
    {
        var job = await CompletedJobAsync();
        var report = (await GenerateReportAsync(job.Manager, job.WorkOrder.Id)).Report!;
        var before = await job.Manager.GetByteArrayAsync($"/api/work-orders/{job.WorkOrder.Id}/report");

        var approved = await ApproveWorkOrderAsync(job.Manager, job.WorkOrder.Id);
        var again = await PostGenerateReportAsync(job.Manager, job.WorkOrder.Id);

        Assert.True(approved.Report!.IsLocked);
        Assert.Equal(HttpStatusCode.Conflict, again.StatusCode);
        Assert.Equal($"This job is Approved, so its service report {report.ReportNumber} is locked and cannot be regenerated.",
            await DetailAsync(again));
        Assert.Equal(before, await job.Manager.GetByteArrayAsync($"/api/work-orders/{job.WorkOrder.Id}/report"));
        Assert.Equal(1, Assert.Single(await ReportRowsAsync(job.WorkOrder.Id)).Revision);
    }

    [Fact]
    public async Task A_job_approved_without_a_report_can_get_exactly_one()
    {
        var job = await CompletedJobAsync();
        await ApproveWorkOrderAsync(job.Manager, job.WorkOrder.Id);

        var first = await PostGenerateReportAsync(job.Manager, job.WorkOrder.Id);
        var second = await PostGenerateReportAsync(job.Manager, job.WorkOrder.Id);

        Assert.Equal(HttpStatusCode.OK, first.StatusCode);
        var report = (await first.Content.ReadFromJsonAsync<WorkOrderDto>())!.Report!;
        Assert.Equal((1, true), (report.Revision, report.IsLocked));
        Assert.Equal(HttpStatusCode.Conflict, second.StatusCode);
    }

    [Fact]
    public async Task Unfinished_or_cancelled_jobs_have_no_report_to_generate_or_download()
    {
        var admin = await _factory.AdminClientAsync();
        var manager = await _factory.ClientWithRoleAsync(AppRoles.Manager);
        var (technician, user) = await _factory.ClientAndUserWithRoleAsync(AppRoles.Technician);
        var assigned = await CreateAssignedWorkOrderAsync(admin, manager, user.Id);
        var inProgress = await CreateInProgressWorkOrderAsync(admin, manager, technician, user.Id);
        var cancelled = await CancelWorkOrderAsync(manager, (await CreateAssignedWorkOrderAsync(admin, manager, user.Id)).Id);

        foreach (var (job, expected) in new[]
                 {
                     (assigned, "This job is Assigned; a service report can only be generated once the job is completed."),
                     (inProgress, "This job is InProgress; a service report can only be generated once the job is completed."),
                     (cancelled, "This job is Cancelled; a cancelled job has no service report.")
                 })
        {
            var response = await PostGenerateReportAsync(manager, job.Id);
            Assert.Equal(HttpStatusCode.Conflict, response.StatusCode);
            Assert.Equal(expected, await DetailAsync(response));

            var download = await manager.GetAsync($"/api/work-orders/{job.Id}/report");
            Assert.Equal(HttpStatusCode.NotFound, download.StatusCode);
            Assert.Equal("This job has no service report yet.", await DetailAsync(download));
            Assert.Empty(await ReportRowsAsync(job.Id));
        }

        Assert.Equal(HttpStatusCode.NotFound, (await PostGenerateReportAsync(manager, int.MaxValue)).StatusCode);
    }

    [Fact]
    public async Task Another_technician_cannot_see_or_download_the_report()
    {
        var job = await CompletedJobAsync();
        await GenerateReportAsync(job.Manager, job.WorkOrder.Id);
        var other = await _factory.ClientWithRoleAsync(AppRoles.Technician);

        var response = await other.GetAsync($"/api/work-orders/{job.WorkOrder.Id}/report");

        Assert.Equal(HttpStatusCode.NotFound, response.StatusCode);
        Assert.Equal("Work order not found.", await DetailAsync(response));
    }

    [Fact]
    public async Task The_reports_list_shows_every_report_newest_first_with_its_job()
    {
        var older = await CompletedJobAsync();
        var newer = await CompletedJobAsync();
        var olderReport = (await GenerateReportAsync(older.Manager, older.WorkOrder.Id)).Report!;
        var newerReport = (await GenerateReportAsync(newer.Manager, newer.WorkOrder.Id)).Report!;
        await ApproveWorkOrderAsync(older.Manager, older.WorkOrder.Id);
        var staff = await _factory.ClientWithRoleAsync(AppRoles.ServiceStaff);

        var reports = (await staff.GetFromJsonAsync<List<ServiceReportDto>>("/api/reports"))!;

        var numbers = reports.Select(r => r.ReportNumber).ToList();
        Assert.True(numbers.IndexOf(newerReport.ReportNumber) < numbers.IndexOf(olderReport.ReportNumber));
        var row = Assert.Single(reports, r => r.ReportNumber == olderReport.ReportNumber);
        Assert.Equal(older.WorkOrder.Id, row.WorkOrderId);
        Assert.Equal(("Approved", true), (row.WorkOrderStatus, row.IsLocked));
        Assert.Equal(older.WorkOrder.CustomerName, row.CustomerName);
        Assert.Equal((older.WorkOrder.EquipmentSerialNumber, older.WorkOrder.EquipmentType), (row.EquipmentSerialNumber, row.EquipmentType));
        Assert.Equal("Test Technician", row.TechnicianName);
        Assert.Equal(("Test Manager", 1), (row.GeneratedByName, row.Revision));
        Assert.NotNull(row.CompletedAt);
        Assert.False(Assert.Single(reports, r => r.ReportNumber == newerReport.ReportNumber).IsLocked);
    }

    // ---- Concurrency and failure ----

    [Fact]
    public async Task Reports_generated_in_parallel_for_different_jobs_get_unique_numbers()
    {
        var jobs = new List<Job>();
        for (var i = 0; i < 6; i++)
        {
            jobs.Add(await CompletedJobAsync());
        }

        var responses = await Task.WhenAll(jobs.Select(j => PostGenerateReportAsync(j.Manager, j.WorkOrder.Id)));

        Assert.All(responses, r => Assert.Equal(HttpStatusCode.OK, r.StatusCode));
        var numbers = await Task.WhenAll(responses.Select(async r => (await r.Content.ReadFromJsonAsync<WorkOrderDto>())!.Report!.ReportNumber));
        Assert.All(numbers, n => Assert.Matches(ReportNumber, n));
        Assert.Equal(numbers.Length, numbers.Distinct().Count());
    }

    [Fact]
    public async Task Parallel_generation_of_one_job_leaves_one_consistent_report_and_one_file()
    {
        var storage = new InMemoryFileStorage();
        await using var host = _factory.WithFileStorage(storage);
        var job = await CompletedJobAsync(host);

        var responses = await Task.WhenAll(Enumerable.Range(0, 5).Select(_ => PostGenerateReportAsync(job.Manager, job.WorkOrder.Id)));

        Assert.All(responses, r => Assert.Contains(r.StatusCode, new[] { HttpStatusCode.OK, HttpStatusCode.Conflict }));
        var winners = await Task.WhenAll(responses.Where(r => r.StatusCode == HttpStatusCode.OK)
            .Select(async r => (await r.Content.ReadFromJsonAsync<WorkOrderDto>())!.Report!));
        Assert.NotEmpty(winners);
        Assert.Single(winners.Select(w => w.ReportNumber).Distinct()); // one number, however many renderings won
        var (number, revision, key) = Assert.Single(await ReportRowsAsync(job.WorkOrder.Id));
        Assert.Equal((winners[0].ReportNumber, winners.Length), (number, revision));
        Assert.Equal(key, Assert.Single(ReportFiles(storage, job.WorkOrder.Id))); // losers and replaced files cleaned up
    }

    [Fact]
    public async Task A_storage_outage_fails_generation_and_records_no_report()
    {
        var job = await CompletedJobAsync();
        var managerUser = await TestUsers.CreateAsync(job.Admin, AppRoles.Manager);
        await using var host = _factory.WithFileStorage(new InMemoryFileStorage { FailSaves = true });
        var manager = await host.SignInAsync(managerUser);

        var response = await PostGenerateReportAsync(manager, job.WorkOrder.Id);

        Assert.Equal(HttpStatusCode.InternalServerError, response.StatusCode);
        Assert.DoesNotContain("Simulated", await DetailAsync(response)); // no internals leak to the client
        Assert.Empty(await ReportRowsAsync(job.WorkOrder.Id));
    }

    [Fact]
    public async Task A_photo_or_signature_missing_from_storage_becomes_a_placeholder_not_a_failed_report()
    {
        var job = await CompletedJobAsync(); // its files are in Azurite, not in the empty fake below
        var managerUser = await TestUsers.CreateAsync(job.Admin, AppRoles.Manager);
        var storage = new InMemoryFileStorage();
        await using var host = _factory.WithFileStorage(storage);
        var manager = await host.SignInAsync(managerUser);

        var response = await PostGenerateReportAsync(manager, job.WorkOrder.Id);

        Assert.Equal(HttpStatusCode.OK, response.StatusCode);
        var pdf = Encoding.Latin1.GetString(await manager.GetByteArrayAsync($"/api/work-orders/{job.WorkOrder.Id}/report"));
        Assert.DoesNotContain("/Subtype /Image", pdf);
    }
